// Разбор разметки выделения → [{ text, bold, italic, underline }]
export function parseMarks(src) {
  const runs = [];
  const state = { bold: false, italic: false, underline: false };
  let buf = '';
  const flush = () => {
    if (!buf) return;
    const last = runs[runs.length - 1];
    if (last && last.bold === state.bold && last.italic === state.italic && last.underline === state.underline) last.text += buf;
    else runs.push({ text: buf, ...state });
    buf = '';
  };
  for (let i = 0; i < src.length; ) {
    if (src.startsWith('***', i)) {
      flush();
      state.bold = !state.bold;
      state.italic = !state.italic;
      i += 3;
    } else if (src.startsWith('**', i)) {
      flush();
      state.bold = !state.bold;
      i += 2;
    } else if (src.startsWith('__', i)) {
      flush();
      state.underline = !state.underline;
      i += 2;
    } else if (src[i] === '*') {
      flush();
      state.italic = !state.italic;
      i += 1;
    } else {
      buf += src[i];
      i += 1;
    }
  }
  flush();
  return runs;
}

export const plain = (src) => parseMarks(src).map((r) => r.text).join('');
